/** Generate both public transport projections; --check never rewrites source files. */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const root = fileURLToPath(new URL("../", import.meta.url));
const check = process.argv.includes("--check");
const projections = [
  ["contracts/openapi-llm-v1.json", "src/types/api-generated.ts"],
  ["contracts/openapi-v1.json", "src/types/api/v1.ts"],
];
let stale = false;
for (const [input, output] of projections) {
  const source = astToString(
    await openapiTS(pathToFileURL(path.join(root, input)), {
      // Request fields with server defaults remain optional on the wire.
      // Preserve the existing LLM projection's options for compatibility.
      ...(input.endsWith("openapi-v1.json") ? { defaultNonNullable: false } : {}),
    }),
  );
  // Keep the upstream CLI's generated-file notice, including its blank line.
  const generated =
    "/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n" +
    source;
  const destination = path.join(root, output);
  if (check) {
    const current = await readFile(destination, "utf8").catch((error) => {
      if (error.code === "ENOENT") return null;
      throw error;
    });
    if (current !== generated) {
      console.error(`${output} is stale. Run npm run generate:types in frontend/.`);
      stale = true;
    }
  } else {
    await mkdir(path.dirname(destination), { recursive: true });
    await writeFile(destination, generated);
    console.log(`Generated ${output}`);
  }
}
if (stale) process.exitCode = 1;
